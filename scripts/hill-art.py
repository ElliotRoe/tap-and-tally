"""Prints the sandy hill and saguaro that peek out behind the card in the app drawings
(hero, roster and menu), with the same texture as the desert footer. It also writes a
Roman copy of each drawing (hero-roman.svg and so on): a sage hill with a cypress, and
the card's accents in purple.
Run from the repo root: python3 scripts/hill-art.py"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from print_texture import Print  # noqa: E402

ART = Path(__file__).parent.parent / "src/lib/art/svg"


def hill(prefix):
    # Drawn about the saguaro's foot; the group is placed behind the card's top-right corner.
    P = Print(prefix, (-130, -120, 290, 200))
    P.shape("back", "M-20 54C-4 22 30 6 64 6s54 18 58 36c3 12-10 18-40 18H6c-20 0-30-2-26-6z", "#f3dcc0", [
        ("fine", "#d9bb98", P.down(6, 60, 0, .6)),
    ])
    P.shape("front", "M-110 50C-92 2-46-24 0-24s88 24 98 58c4 16-14 24-54 24h-118c-30 0-42-4-36-8z", "#ebc7a0", [
        ("fine", "#c69670", P.down(-24, 60, 0, .75)),
        ("coarse", "#d2a178", P.across(-20, 100, 0, .5)),
    ])
    P.shape("lit", "M-110 50C-92 2-46-24 0-24c-26 10-44 38-50 82h-34c-30 0-42-4-36-8z", "#f1d5b4", [
        ("speck", "#fbecd8", P.down(-24, 20, .9, 0)),
    ])
    P.saguaro("cactus", 0, -20, 20, 88, ["M-2 -34H-24V-58", "M2 -48H22V-72"], 11, dark="#5f7a4c", light="#7a9562")
    return P


def roman_hill(prefix):
    # The same hill in sage, with a cypress standing on it, clear of the card.
    P = Print(prefix, (-130, -120, 290, 200))
    P.shape("back", "M-20 54C-4 22 30 6 64 6s54 18 58 36c3 12-10 18-40 18H6c-20 0-30-2-26-6z", "#e6e3c6", [
        ("fine", "#cbc7a0", P.down(6, 60, 0, .6)),
    ])
    P.shape("front", "M-110 50C-92 2-46-24 0-24s88 24 98 58c4 16-14 24-54 24h-118c-30 0-42-4-36-8z", "#d8d4aa", [
        ("fine", "#b3ae80", P.down(-24, 60, 0, .75)),
        ("coarse", "#c1bc90", P.across(-20, 100, 0, .5)),
    ])
    P.shape("lit", "M-110 50C-92 2-46-24 0-24c-26 10-44 38-50 82h-34c-30 0-42-4-36-8z", "#e9e6cd", [
        ("speck", "#f4f2e3", P.down(-24, 20, .9, 0)),
    ])
    P.cypress("cypress", 46, -10, 24, 100)  # beside the card, so its whole shape shows
    return P


# The Roman copies recolour the card's accents and rename its ids so both can share a page.
ROMAN_COLOURS = {"#b4532a": "#6e2d6a", "#7a3418": "#451a43"}


def print_hill(svg, P):
    block = (
        "  <!-- hill:start: generated by scripts/hill-art.py -->\n"
        '  <g transform="translate(468 128)">\n    '
        + P.body("    ")
        + "\n  </g>\n  <!-- hill:end -->\n"
    )
    defs = f"    <!-- hill-defs:start -->\n{P.defs()}\n    <!-- hill-defs:end -->\n"
    svg = re.sub(r"  <!-- hill:start.*?<!-- hill:end -->\n", lambda _: block, svg, flags=re.S)
    return re.sub(r"    <!-- hill-defs:start -->.*?<!-- hill-defs:end -->\n", lambda _: defs, svg, flags=re.S)


for name in ["hero", "roster", "menu"]:
    path = ART / f"{name}.svg"
    svg = path.read_text()
    # First run: swap the flat hill for markers; later runs: replace between them.
    svg = re.sub(r"  <!-- Sandy hills.*?\n  </g>\n", "  <!-- hill:start -->\n  <!-- hill:end -->\n", svg, flags=re.S)
    if "hill-defs:start" not in svg:
        svg = svg.replace("  </defs>", "    <!-- hill-defs:start -->\n    <!-- hill-defs:end -->\n  </defs>", 1)
    path.write_text(print_hill(svg, hill(f"{name}-hill")))

    roman = re.sub(rf'(id="|url\(#){name}-', rf"\1{name}-roman-", svg)
    for western, purple in ROMAN_COLOURS.items():
        roman = re.sub(western, purple, roman, flags=re.I)
    (ART / f"{name}-roman.svg").write_text(print_hill(roman, roman_hill(f"{name}-roman-hill")))
    print(name, "printed, with its Roman copy")

# The hill on its own, for drawings built from the page itself (the "What you track" preview).
for name, P in [("hill", hill("hill")), ("hill-roman", roman_hill("hill-roman"))]:
    (ART / f"{name}.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="-130 -120 290 200">\n'
        "  <!-- Generated by scripts/hill-art.py: edit that, not this file. -->\n"
        f"  <defs>\n{P.defs()}\n  </defs>\n  {P.body()}\n</svg>\n"
    )
    print(name, "printed on its own")
